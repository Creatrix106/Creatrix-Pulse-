"use client";

import { useState } from "react";
import { EmptyState } from "@/components/feedback/empty-state";
import { QueryBoundary } from "@/components/feedback/query-boundary";
import { InsightCard, insightTypeConfig } from "@/components/dashboard/insight-card";
import { useInsightsQuery } from "@/hooks/use-analytics";
import type { Insight, InsightType } from "@/types/insight";
import { cn } from "@/utils/cn";

const ORDER: InsightType[] = ["positive", "negative", "anomaly", "observation", "recommendation"];

function InsightsContent({ insights }: { insights: Insight[] }) {
  const [filter, setFilter] = useState<InsightType | "all">("all");

  if (insights.length === 0) {
    return <EmptyState title="No insights for this selection" description="Insights are generated by the analytics engine from your data. Try a wider date range or enable a comparison period." />;
  }

  const counts = ORDER.map((type) => ({ type, count: insights.filter((i) => i.type === type).length })).filter((c) => c.count > 0);
  const visible = (filter === "all" ? [...insights] : insights.filter((i) => i.type === filter)).sort((a, b) => ORDER.indexOf(a.type) - ORDER.indexOf(b.type));
  const chip = "inline-flex items-center gap-1.5 rounded-full border px-3 py-1.5 text-sm font-medium transition-colors";

  return (
    <div className="space-y-5">
      <div role="group" aria-label="Filter insights by type" className="flex flex-wrap gap-2">
        <button type="button" aria-pressed={filter === "all"} onClick={() => setFilter("all")} className={cn(chip, filter === "all" ? "border-transparent bg-primary text-primary-foreground" : "border-border bg-surface text-foreground hover:bg-surface-accent")}>
          All <span className="tabular opacity-80">{insights.length}</span>
        </button>
        {counts.map(({ type, count }) => {
          const Icon = insightTypeConfig[type].icon;
          return (
            <button key={type} type="button" aria-pressed={filter === type} onClick={() => setFilter(type)} className={cn(chip, filter === type ? "border-transparent bg-primary text-primary-foreground" : "border-border bg-surface text-foreground hover:bg-surface-accent")}>
              <Icon className="size-4" aria-hidden /> {insightTypeConfig[type].label} <span className="tabular opacity-80">{count}</span>
            </button>
          );
        })}
      </div>
      <div className="grid gap-4 xl:grid-cols-2">
        {visible.map((insight) => (
          <InsightCard key={insight.id} insight={insight} />
        ))}
      </div>
      <p className="text-xs text-muted">Insights are computed by the analytics service from the selected data and filters. Each card lists the figures it is based on.</p>
    </div>
  );
}

export function InsightsView() {
  const query = useInsightsQuery();
  return <QueryBoundary query={query}>{(insights) => <InsightsContent insights={insights} />}</QueryBoundary>;
}
